// Scans packages/geometry/templates for JSON and generates
// src/template-catalog.generated.ts with inlined definitions.
// Add a new template JSON, then run: npm run templates:sync -w @boq/geometry

import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { dirname, join, relative } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG = join(__dirname, '..');
const TEMPLATES = join(PKG, 'templates');
const OUT = join(PKG, 'src', 'template-catalog.generated.ts');

function walk(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const name of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, name.name);
    if (name.isDirectory()) walk(p, acc);
    else if (name.name.endsWith('.json')) acc.push(p);
  }
  return acc;
}

const files = walk(TEMPLATES).sort();
if (files.length === 0) {
  console.warn('No template JSON found. Run: node scripts/seed-house-templates.mjs');
}

const entries = files.map((abs) => {
  const sourcePath = relative(TEMPLATES, abs).replace(/\\/g, '/');
  const raw = JSON.parse(readFileSync(abs, 'utf8'));
  const def = JSON.stringify(raw, null, 2)
    .split('\n')
    .map((line, i) => (i === 0 ? line : `    ${line}`))
    .join('\n');
  return `  {\n    definition: ${def} as HouseTemplateDefinition,\n    sourcePath: ${JSON.stringify(sourcePath)},\n  }`;
});

const body = `// AUTO-GENERATED by scripts/sync-templates.mjs — do not edit by hand
import type { HouseTemplateDefinition, TemplateCatalogEntry } from './template-schema';

export const TEMPLATE_CATALOG: TemplateCatalogEntry[] = [
${entries.join(',\n')}
];
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`Generated ${OUT} with ${files.length} templates.`);
